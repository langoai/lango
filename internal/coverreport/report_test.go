func TestAnalyzeProfile_ExcludesGeneratedPathsAndMarkers(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "internal/live/live.go", "package live\n")
	writeFile(t, root, "internal/live/manual.go", "// DO NOT EDIT config by hand.\npackage live\n")
	writeFile(t, root, "internal/live/header_mentions.go", "// This test mentions Code generated and DO NOT EDIT.\npackage live\n")
	writeFile(t, root, "internal/live/mentions.go", "package live\n\nconst marker = \"Code generated DO NOT EDIT\"\n")
	writeFile(t, root, "internal/ent/user.go", "package ent\n")
	writeFile(t, root, "internal/generated/marker.go", "// Code generated by test. DO NOT EDIT.\npackage generated\n")

	profile := writeProfile(t, root, []string{
		"mode: set",
		"github.com/langoai/lango/internal/live/live.go:1.1,2.1 10 1",
		"github.com/langoai/lango/internal/live/live.go:3.1,4.1 5 0",
		"github.com/langoai/lango/internal/live/manual.go:1.1,2.1 3 1",
		"github.com/langoai/lango/internal/live/header_mentions.go:1.1,2.1 6 1",
		"github.com/langoai/lango/internal/live/mentions.go:1.1,3.1 4 1",
		"github.com/langoai/lango/internal/ent/user.go:1.1,2.1 100 0",
		"github.com/langoai/lango/internal/generated/marker.go:1.1,2.1 200 0",
	})

	report, err := AnalyzeProfile(context.Background(), Options{
		ProfilePath: profile,
		RootDir:     root,
		ModulePath:  "github.com/langoai/lango",
		TopLimit:    10,
	})
	if err != nil {
		t.Fatalf("AnalyzeProfile returned error: %v", err)
	}

	if report.TotalStatements != 28 {
		t.Fatalf("total statements = %d, want 28", report.TotalStatements)
	}
	if report.CoveredStatements != 23 {
		t.Fatalf("covered statements = %d, want 23", report.CoveredStatements)
	}
	if report.UncoveredStatements != 5 {
		t.Fatalf("uncovered statements = %d, want 5", report.UncoveredStatements)
	}
	wantFiles := "internal/live/header_mentions.go,internal/live/live.go,internal/live/manual.go,internal/live/mentions.go"
	if got := strings.Join(filePaths(report.Files), ","); got != wantFiles {
		t.Fatalf("included files = %s, want %s", got, wantFiles)
	}
}

func TestAnalyzeProfile_AggregatesByFileAndSortsTopUncovered(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "internal/a.go", "package internal\n")
	writeFile(t, root, "internal/b.go", "package internal\n")
	writeFile(t, root, "internal/c.go", "package internal\n")

	profile := writeProfile(t, root, []string{
		"mode: atomic",
		"github.com/langoai/lango/internal/a.go:1.1,2.1 10 0",
		"github.com/langoai/lango/internal/a.go:3.1,4.1 5 1",
		"github.com/langoai/lango/internal/b.go:1.1,2.1 7 0",
		"github.com/langoai/lango/internal/c.go:1.1,2.1 9 1",
	})

	report, err := AnalyzeProfile(context.Background(), Options{
		ProfilePath: profile,
		RootDir:     root,
		ModulePath:  "github.com/langoai/lango",
		TopLimit:    2,
	})
	if err != nil {
		t.Fatalf("AnalyzeProfile returned error: %v", err)
	}

	if report.TotalStatements != 31 {
		t.Fatalf("total statements = %d, want 31", report.TotalStatements)
	}
	if report.CoveredStatements != 14 {
		t.Fatalf("covered statements = %d, want 14", report.CoveredStatements)
	}
	if report.UncoveredStatements != 17 {
		t.Fatalf("uncovered statements = %d, want 17", report.UncoveredStatements)
	}
	if got := filePaths(report.TopUncovered); strings.Join(got, ",") != "internal/a.go,internal/b.go" {
		t.Fatalf("top uncovered paths = %v, want internal/a.go, internal/b.go", got)
	}
}

func TestCheckThreshold_PassesAtOrAboveThreshold(t *testing.T) {
	report := Report{
		CoveredStatements: 90,
		TotalStatements:   100,
	}

	if err := CheckThreshold(report, 90); err != nil {
		t.Fatalf("CheckThreshold returned error: %v", err)
	}
}

func TestCheckThreshold_FailsBelowThreshold(t *testing.T) {
	report := Report{
		CoveredStatements: 89,
		TotalStatements:   100,
	}

	err := CheckThreshold(report, 90)
	if err == nil {
		t.Fatal("CheckThreshold returned nil, want threshold error")
	}
	if !strings.Contains(err.Error(), "89.00%") || !strings.Contains(err.Error(), "90.00%") {
		t.Fatalf("threshold error = %q, want measured and required percentages", err.Error())
	}
}

func writeFile(t *testing.T, root, rel, content string) {
	t.Helper()

	path := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("MkdirAll(%q) returned error: %v", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("WriteFile(%q) returned error: %v", path, err)
	}
}

func writeProfile(t *testing.T, root string, lines []string) string {
	t.Helper()

	path := filepath.Join(root, "coverage.out")
	if err := os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o644); err != nil {
		t.Fatalf("WriteFile(%q) returned error: %v", path, err)
	}
	return path
}

func filePaths(files []FileCoverage) []string {
	paths := make([]string, 0, len(files))
	for _, file := range files {
		paths = append(paths, file.Path)
	}
	return paths
}
